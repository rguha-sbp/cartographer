import json
from pathlib import Path
from xml.etree import ElementTree

from cartographer import drift, files, index
from cartographer.svg_export import SOURCE_SHA_ATTR


def _pair(folder: Path, name: str, image_sha: str | None = None, drawio: str = "<mxfile/>") -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{name}.drawio"
    path.write_text(drawio)
    sha = image_sha or files.sha256_file(path)
    (folder / f"{name}.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" {SOURCE_SHA_ATTR}="{sha}"/>')
    return path


def test_image_path_is_the_sibling_svg() -> None:
    assert files.image_path(Path("d/a-l7.drawio")) == Path("d/a-l7.svg")
    assert files.image_path(Path("d/a-l7.generated.drawio")) == Path("d/a-l7.generated.svg")


def test_hand_edit_is_a_sha_mismatch_or_a_missing_record(tmp_path: Path) -> None:
    drawio = tmp_path / "a.drawio"
    assert not files.hand_edited(drawio, {})
    drawio.write_text("<mxfile/>")
    assert files.hand_edited(drawio, {})
    assert files.hand_edited(drawio, {"drawio_sha256": "0" * 64})
    assert not files.hand_edited(drawio, {"drawio_sha256": files.sha256_file(drawio)})


def test_record_keeps_the_rest_of_the_curated_file(tmp_path: Path) -> None:
    curated = tmp_path / "a.curated.json"
    curated.write_text(json.dumps({"z": 1, "a": {"é": [1, 2]}}))
    files.record_sha256(curated, "f" * 64)
    assert curated.read_text() == json.dumps({"z": 1, "a": {"é": [1, 2]}, "drawio_sha256": "f" * 64},
                                             indent=2, ensure_ascii=False) + "\n"
    files.record_sha256(curated, "e" * 64)
    assert json.loads(curated.read_text())["drawio_sha256"] == "e" * 64
    assert list(json.loads(curated.read_text())) == ["z", "a", "drawio_sha256"]


def test_check_passes_for_matching_images(tmp_path: Path) -> None:
    _pair(tmp_path, "a-l7")
    _pair(tmp_path / "deeper", "b-l7")
    assert drift.problems(tmp_path) == []


def test_check_reports_missing_unparsable_and_stale_images(tmp_path: Path) -> None:
    _pair(tmp_path, "stale", image_sha="0" * 64)
    (tmp_path / "missing.drawio").write_text("<mxfile/>")
    broken = _pair(tmp_path, "broken")
    files.image_path(broken).write_text("<svg")
    plain = _pair(tmp_path, "plain")
    files.image_path(plain).write_text("<svg/>")
    found = drift.problems(tmp_path)
    assert len(found) == 4
    assert any("missing.drawio" in p and "no image" in p for p in found)
    assert any("stale.drawio" in p and "does not match" in p for p in found)
    assert any("broken.svg" in p and "not valid XML" in p for p in found)
    assert any("plain.drawio" in p and "does not match" in p for p in found)


def _book(folder: Path, stamp: str | None = None) -> Path:
    drawio = folder / "shop-c4.drawio"
    drawio.write_text(BOOK)
    for page in files.pages(drawio, BOOK):
        page.image.write_text(f'<svg {SOURCE_SHA_ATTR}="{stamp or files.sha256_file(drawio)}"/>')
    return drawio


def test_check_wants_an_image_of_the_whole_file_for_every_page_of_a_book(tmp_path: Path) -> None:
    drawio = _book(tmp_path)
    assert drift.problems(tmp_path) == []
    (tmp_path / "shop-c4-2-container.svg").unlink()
    assert drift.problems(tmp_path) == [f"{drawio}: no image, run `cartographer image {drawio}`"]
    _book(tmp_path, stamp="0" * 64)
    assert len(drift.problems(tmp_path)) == 2


def test_check_ignores_side_files_and_curated_files(tmp_path: Path) -> None:
    (tmp_path / "a.generated.drawio").write_text("<mxfile/>")
    (tmp_path / "a.curated.json").write_text("{}")
    assert drift.problems(tmp_path) == []


def test_index_lists_one_line_per_drawio(tmp_path: Path) -> None:
    (tmp_path / "shop-c4-2-container.drawio").write_text('<mxfile><diagram name="Container diagram for Shop"/></mxfile>')
    (tmp_path / "shop-c4-1-context.drawio").write_text('<mxfile><diagram name="System Context diagram for Shop"/></mxfile>')
    (tmp_path / "gip.drawio").write_text('<mxfile><diagram name="Layer 7 diagram for GIP"/></mxfile>')
    (tmp_path / "gip.generated.drawio").write_text('<mxfile><diagram name="Layer 7 diagram for GIP"/></mxfile>')
    index.write_index(tmp_path)
    lines = (tmp_path / "README.md").read_text().splitlines()
    assert "generated by cartographer" in lines[0].lower()
    assert "| Diagram | Source | Image |" in lines
    rows = [line for line in lines if ".drawio](" in line]
    expected = [("Layer 7 diagram for GIP", "gip"), ("System Context diagram for Shop", "shop-c4-1-context"),
                ("Container diagram for Shop", "shop-c4-2-container")]
    assert rows == [f"| {title} | [{s}.drawio]({s}.drawio) | [{s}.svg]({s}.svg) |" for title, s in expected]


def test_index_lists_one_line_per_page_of_a_book(tmp_path: Path) -> None:
    _book(tmp_path)
    index.write_index(tmp_path)
    rows = [line for line in (tmp_path / "README.md").read_text().splitlines() if ".drawio](" in line]
    assert rows == [f"| {title} | [shop-c4.drawio](shop-c4.drawio) | [shop-c4-{s}.svg](shop-c4-{s}.svg) |"
                    for title, s in (("Context", "1-context"), ("Container", "2-container"))]


def test_index_text_has_no_dashes_or_smart_quotes(tmp_path: Path) -> None:
    (tmp_path / "a-l7.drawio").write_text('<mxfile><diagram name="Layer 7 diagram for A"/></mxfile>')
    index.write_index(tmp_path)
    assert "| Layer 7 diagram for A | [a-l7.drawio]" in (tmp_path / "README.md").read_text()
    assert not [c for c in (tmp_path / "README.md").read_text() if c in "—–‘’“”"]


def test_index_titles_a_drawio_without_a_page_name_by_its_file_name(tmp_path: Path) -> None:
    (tmp_path / "a-l7.curated.json").write_text(json.dumps({"system": "A", "view": "l7"}))
    (tmp_path / "a-l7.drawio").write_text("<mxfile/>")
    (tmp_path / "b.drawio").write_text("not xml")
    index.write_index(tmp_path)
    readme = (tmp_path / "README.md").read_text()
    assert "| a-l7 | [a-l7.drawio]" in readme and "| b | [b.drawio]" in readme


BOOK = ('<mxfile host="h"><diagram id="1-context" name="Context"><mxGraphModel/></diagram>'
        '<diagram id="2-container" name="Container"><mxGraphModel/></diagram></mxfile>')


def test_a_one_page_file_is_drawn_whole_into_its_sibling_image(tmp_path: Path) -> None:
    d = tmp_path / "a.drawio"
    for text, name in (('<mxfile><diagram name="S"/></mxfile>', "S"), ("<mxfile/>", ""),
                       ("<mxfile><diagram/></mxfile>", ""), ("not xml", "")):
        assert files.pages(d, text) == [files.Page(name, tmp_path / "a.svg", text)]


def test_each_page_of_a_book_is_drawn_alone_into_an_image_named_for_its_page(tmp_path: Path) -> None:
    context, container = files.pages(tmp_path / "shop-c4.drawio", BOOK)
    assert (context.name, context.image) == ("Context", tmp_path / "shop-c4-1-context.svg")
    assert (container.name, container.image) == ("Container", tmp_path / "shop-c4-2-container.svg")
    assert context.mxfile == ('<mxfile host="h">\n  <diagram id="1-context" name="Context">\n'
                              "    <mxGraphModel />\n  </diagram>\n</mxfile>\n")


def test_a_page_split_from_a_book_is_the_one_page_file_of_that_page() -> None:
    def page(n: str) -> ElementTree.Element:
        p = ElementTree.Element("diagram", id=f"x-{n}", name=f"it's {n}")
        ElementTree.SubElement(ElementTree.SubElement(p, "mxGraphModel"), "root")
        return p

    book = files.pages(Path("x-c4.drawio"), files.mxfile([page("a"), page("b")]))
    assert [p.mxfile for p in book] == [files.mxfile([page("a")]), files.mxfile([page("b")])]
