"""The generated README.md of a diagrams folder: one line per page of each .drawio, side files excluded."""

from pathlib import Path

from cartographer import files

HEADER = """This file is generated by cartographer. Do not edit it by hand.

# Architecture diagrams

| Diagram | Source | Image |
|---|---|---|
"""


def _row(drawio: Path, page: files.Page) -> str:
    svg = page.image.name
    return f"| {page.name or drawio.stem} | [{drawio.name}]({drawio.name}) | [{svg}]({svg}) |"


def write_index(folder: Path) -> None:
    drawios = (p for p in sorted(folder.glob("*.drawio")) if not files.is_side_file(p))
    rows = [_row(drawio, page) for drawio in drawios for page in files.pages(drawio, drawio.read_text())]
    (folder / "README.md").write_text(HEADER + "\n".join(rows) + "\n")
