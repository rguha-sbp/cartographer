"""The generated README.md of a diagrams folder: one line per .drawio, side files excluded."""

import json
from pathlib import Path
from xml.etree import ElementTree

from cartographer import files, tfdiagram

CURATED_SUFFIX = ".curated.json"
HEADER = """This file is generated by cartographer. Do not edit it by hand.

# Architecture diagrams

| Diagram | Source | Image |
|---|---|---|
"""


def _title(drawio: Path) -> str:
    """The name of the first page; without one, the title of the curated file beside it, else the file name."""
    try:
        page = ElementTree.parse(drawio).getroot().find("diagram")
    except ElementTree.ParseError:
        page = None
    if page is not None and page.get("name"):
        return page.get("name")
    curated = drawio.with_name(drawio.stem + CURATED_SUFFIX)
    return tfdiagram.diagram_title(json.loads(curated.read_text())) if curated.is_file() else drawio.stem


def _row(drawio: Path) -> str:
    svg = files.image_path(drawio).name
    return f"| {_title(drawio)} | [{drawio.name}]({drawio.name}) | [{svg}]({svg}) |"


def write_index(folder: Path) -> None:
    rows = [_row(p) for p in sorted(folder.glob("*.drawio")) if not files.is_side_file(p)]
    (folder / "README.md").write_text(HEADER + "\n".join(rows) + "\n")
