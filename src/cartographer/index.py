"""The generated README.md of a diagrams folder: one line per curated file."""

import json
from pathlib import Path

from cartographer import tfdiagram

CURATED_SUFFIX = ".curated.json"
HEADER = """This file is generated by cartographer. Do not edit it by hand.

# Architecture diagrams

| View | Diagram | Source | Image |
|---|---|---|---|
"""


def _row(curated_path: Path) -> str:
    name = curated_path.name.removesuffix(CURATED_SUFFIX)
    curated = json.loads(curated_path.read_text())
    return (f"| {curated['view']} | {tfdiagram.diagram_title(curated)} | [{name}.drawio]({name}.drawio) "
            f"| [{name}.svg]({name}.svg) |")


def write_index(folder: Path) -> None:
    rows = [_row(p) for p in sorted(folder.glob(f"*{CURATED_SUFFIX}"))]
    (folder / "README.md").write_text(HEADER + "\n".join(rows) + "\n")
